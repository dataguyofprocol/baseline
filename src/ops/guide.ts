// What an agent is told about the operations, generated from OPERATIONS so it can't drift: the
// block `baseline connect` puts in AGENTS.md / CLAUDE.md, the MCP server's `instructions`, and the
// hand-off brief's {{tracking}} text (written to src/core/tracking.ts by `npm run gen:skill`).
import { OPERATIONS } from './index.js';
import { usageOf, type AnyOperation, type OpName } from './operation.js';

const opNamed = (name: OpName): AnyOperation => OPERATIONS.find(o => o.name === name)!;
const firstSentence = (s: string) => s.split(/(?<=\.)\s/)[0]!;
/** the command without --json, with the issue argument filled in */
const command = (op: AnyOperation, key?: string) => {
  const u = usageOf(op).replace(/ \[--json\]$/, '');
  return key ? u.replace(/<(issue|from_issue)>/, key) : u;
};

/** the work loop, in the order an agent calls it; typed, so a renamed op fails the build */
const LOOP: readonly OpName[] = ['start_issue', 'get_issue', 'post_progress', 'file_followup', 'finish_issue'];

export const BLOCK_START = '<!-- baseline:agent-tracking:start (generated by `baseline connect`; run it again to update, and edit outside these markers) -->';
export const BLOCK_END = '<!-- baseline:agent-tracking:end -->';

/** The guidance every connected agent reads: in its AGENTS.md / CLAUDE.md block and as MCP instructions. */
export function agentGuide(): string {
  return [
    '## Baseline: keep the tracker current',
    '',
    'This repo\'s work is tracked in Baseline. When you work on a Baseline issue (a key such as ENG-42, from the person or a hand-off brief), keep it current yourself, so the person never has to type the update:',
    '',
    '1. `start_issue` once, before you change code for the issue. Use the branch it returns.',
    '2. `post_progress` after each meaningful step: what you did, what is left, what blocks you. It rewrites one note, so post often.',
    '3. `file_followup` for work you find that is not part of the issue. It goes to Triage for the person.',
    '4. `finish_issue` when you stop: `in_review` (a PR waits), `done`, or `stopped` with what is left.',
    '',
    'If the person asks for work that matches an open issue, find it with `list_issues` and ask whether to track the work on it. Do not publish project updates: `draft_project_update` writes a draft that the person publishes. Each write returns an `op_id`; call `undo` with it only when the person asks.',
    '',
    'Use the tools of the `baseline` MCP server. Without MCP (for example in pi), run the same operation as a `baseline agent` command and add `--as "<your agent name>"` (for example `--as pi`), so the change shows as yours on the person\'s behalf:',
    '',
    ...OPERATIONS.map(op => `- \`${op.name}\` (\`${command(op as AnyOperation)}\`): ${firstSentence(op.description)}`),
  ].join('\n');
}

/** The AGENTS.md / CLAUDE.md block, with its markers. */
export const agentBlock = (): string => `${BLOCK_START}\n${agentGuide()}\n${BLOCK_END}`;

/** The hand-off brief's {{tracking}} text; `{{key}}` is the issue key, filled in by buildHandoff. */
export function handoffTracking(): string {
  return [
    'Track the work on {{key}} in Baseline as you go, with the tools of the `baseline` MCP server or, without MCP, the `baseline agent` commands (add `--as "<your agent name>"`):',
    ...LOOP.map(name => {
      const op = opNamed(name);
      return `- \`${op.name}\` (\`${command(op, '{{key}}')}\`): ${firstSentence(op.description)}`;
    }),
  ].join('\n');
}
