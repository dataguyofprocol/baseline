// What an agent is told about the operations, generated from OPERATIONS so it can't drift: the
// block `baseline connect` puts in AGENTS.md / CLAUDE.md, the MCP server's `instructions`, and the
// hand-off brief's {{tracking}} text (written to src/core/tracking.ts by `npm run gen:skill`).
import { OPERATIONS } from './index.js';
import { usageOf, type AnyOperation, type OpName } from './operation.js';

const opNamed = (name: OpName): AnyOperation => OPERATIONS.find(o => o.name === name)!;
const firstSentence = (s: string) => s.split(/(?<=\.)\s/)[0]!;
/** the command without --json, with the issue argument filled in */
const command = (op: AnyOperation, key?: string) => {
  const u = usageOf(op).replace(/ \[--json\]$/, '');
  return key ? u.replace(/<(issue|from_issue)>/, key) : u;
};

/** the work loop, in the order an agent calls it; typed, so a renamed op fails the build */
const LOOP: readonly OpName[] = ['start_issue', 'get_issue', 'post_progress', 'create_sub_issues', 'propose_followup', 'finish_issue'];

export const BLOCK_START = '<!-- baseline:agent-tracking:start (generated by `baseline connect`; run it again to update, and edit outside these markers) -->';
export const BLOCK_END = '<!-- baseline:agent-tracking:end -->';

/** The guidance every connected agent reads: in its AGENTS.md block and as MCP instructions. */
export function agentGuide(): string {
  return [
    '## Baseline: keep the tracker current',
    '',
    'This repo\'s work is tracked in Baseline. Keep it current yourself, so the person never has to type the update:',
    '',
    '1. Know the issue before you change code. "What should I work on?" is `next_issue`. For a request without a key (a key looks like ENG-42), search the team with `find_issues` and ask once whether to track the work on the match. With no match, `propose_issue` and show the draft; call `create_issue` only after the person says yes in this conversation.',
    '2. `start_issue` once, before you change code. It checks out the issue\'s branch (or gives you the git command). If the issue is another person\'s, ask before you take it over.',
    '3. `post_progress` after each meaningful step: what you did, what is left, what blocks you. It rewrites one note, so post often. Split a started issue with `create_sub_issues` (no need to ask).',
    '4. `propose_followup` for work you find that is not part of the issue. It is only a note until finish.',
    '5. `finish_issue` when you stop: `in_review` (a PR waits), `done`, or `stopped` with what is left. Then ask once about the follow-ups it lists, and `create_issue` the approved ones by draft_id.',
    '',
    '"What did I do since yesterday?" is `my_activity`. Do not publish project updates: `draft_project_update` writes a draft that the person publishes. Each write returns an `op_id`; call `undo` with it only when the person asks.',
    '',
    'Use the tools of the `baseline` MCP server first (named like `mcp__baseline__start_issue`). Only when they are not in this session, run the same operation as a `baseline agent` command; add `--as "<your tool>"` (`Claude Code`, `Codex`, `Cursor` or `pi`; its agent user is made on first use) so the change shows as yours on the person\'s behalf:',
    '',
    ...OPERATIONS.map(op => `- \`${op.name}\` (\`${command(op as AnyOperation)}\`): ${firstSentence(op.description)}`),
  ].join('\n');
}

/** The AGENTS.md block (Codex, pi), with its markers: the whole guide. */
export const agentBlock = (): string => `${BLOCK_START}\n${agentGuide()}\n${BLOCK_END}`;

/** Claude Code's CLAUDE.md block: five lines. The MCP server's instructions carry the full guide
 *  and the hooks (`baseline connect claude`) do the reminding, so the file stays short. */
export function claudeBlock(): string {
  return [
    BLOCK_START,
    '## Baseline',
    'Work here is tracked in Baseline through the `baseline` MCP server (its instructions have the details). Before coding, know the issue: `next_issue`, `find_issues`, or `propose_issue` and `create_issue` only after the person says yes.',
    '`start_issue` once (it checks out the branch), `post_progress` after each meaningful step, `create_sub_issues` to split it, `propose_followup` for unrelated work.',
    '`finish_issue` when you stop, then ask once about the follow-ups it lists. Never publish anything; `undo` takes an op_id only when the person asks.',
    'Without the MCP tools: `baseline agent <tool-name> --help` (dashes for underscores), e.g. `baseline agent start-issue ENG-42`.',
    BLOCK_END,
  ].join('\n');
}

/** The hand-off brief's {{tracking}} text; `{{key}}` is the issue key, filled in by buildHandoff. */
export function handoffTracking(): string {
  return [
    'Track the work on {{key}} in Baseline as you go, with the tools of the `baseline` MCP server or, without MCP, the `baseline agent` commands (add `--as "<your tool>"`, such as `Claude Code` or `Codex`; the /baseline skill has them all, if you have it):',
    ...LOOP.map(name => {
      const op = opNamed(name);
      return `- \`${op.name}\` (\`${command(op, '{{key}}')}\`): ${firstSentence(op.description)}`;
    }),
  ].join('\n');
}
